use anyhow::{Context, Result};
use clap::Parser;
use crossterm::{
    event::{
        DisableBracketedPaste, EnableBracketedPaste, Event as TerminalEvent, EventStream,
        KeyEventKind,
    },
    execute,
};
use futures_util::StreamExt;
use mailtui::{
    app::{App, Overlay, start_worker_with_index},
    config::Config,
    storage::{DemoStore, MailStore, PimdirStore},
    viewer::Viewer,
};
use std::{
    path::PathBuf,
    sync::{
        Arc,
        atomic::{AtomicU64, Ordering},
    },
    time::Duration,
};

#[derive(Parser)]
#[command(
    version,
    about = "Local-first, k9s-inspired mail TUI with live pimdir updates"
)]
struct Args {
    /// Use deterministic offline fixtures; changes are volatile.
    #[arg(long)]
    demo: bool,
    /// Application configuration (default: XDG_CONFIG_HOME/mailtui/config.toml).
    #[arg(short, long)]
    config: Option<PathBuf>,
    /// Print local diagnostics without entering the terminal UI.
    #[arg(long)]
    diagnostics: bool,
    /// Print the actual key registry in Markdown.
    #[arg(long)]
    keybindings: bool,
    /// Render deterministic demo screen at WIDTHxHEIGHT without a terminal.
    #[arg(long, value_name = "WIDTHxHEIGHT")]
    snapshot: Option<String>,
}

#[tokio::main]
async fn main() -> Result<()> {
    let args = Args::parse();
    mailtui::app::validate_bindings()?;
    if args.keybindings {
        println!(
            "# Keyboard reference\n\nGenerated by `mailtui --keybindings`.\n\n| Key | Action |\n|---|---|"
        );
        for b in mailtui::app::bindings() {
            println!("| `{}` | {} |", b.key, b.description);
        }
        return Ok(());
    }
    let mut config = if args.demo && args.config.is_none() {
        Config::default()
    } else {
        Config::load(args.config)?
    };
    if std::env::var_os("NO_COLOR").is_some() || std::env::var("TERM").is_ok_and(|s| s == "dumb") {
        config.ui.theme = "no-color".into();
    }
    let store: Box<dyn MailStore> = if args.demo {
        Box::new(DemoStore::new())
    } else {
        Box::new(PimdirStore::new(config.accounts.clone()))
    };
    if args.diagnostics {
        let result = tokio::task::spawn_blocking(move || -> Result<_> {
            Ok((store.accounts(), store.folders()?, store.pending()?))
        })
        .await??;
        println!(
            "MailTUI {}\nBackend: {}\nAccounts: {}\nFolders: {}\nMessages: {}\nUnread: {}\nOutgoing mail: {}\nMutations: public pimdir producer queue\nLive updates: public pimdir change cursors, every 2s\nSearch: MailTUI local SQLite FTS5 index\nViewer: 127.0.0.1, ephemeral port",
            env!("CARGO_PKG_VERSION"),
            if args.demo {
                "demo (volatile)"
            } else {
                "pimdir"
            },
            result.0.len(),
            result.1.len(),
            result.1.iter().map(|f| f.total).sum::<u64>(),
            result.1.iter().map(|f| f.unread).sum::<u64>(),
            result.2.len()
        );
        return Ok(());
    }
    let current = Arc::new(AtomicU64::new(0));
    let index_path = if args.demo {
        None
    } else {
        let accounts = config.accounts.clone();
        Some(
            tokio::task::spawn_blocking(move || -> Result<PathBuf> {
                let path = mailtui::index::path(&accounts)?;
                mailtui::search::SearchIndex::open(&path)?;
                Ok(path)
            })
            .await??,
        )
    };
    let (tx, mut events, worker) =
        start_worker_with_index(store, current.clone(), index_path.clone());
    let mut app = App::new(args.demo, config.ui.theme.clone(), current.clone(), tx);
    app.llm = config.llm.clone();
    app.configure_pim(config.calendar.clone(), config.contacts.clone());
    app.reload(false);
    app.configure_tasks_and_sync(&config.calendars, &config.tasks);
    if let Some(size) = args.snapshot {
        let (w, h) = size
            .split_once('x')
            .context("Use --snapshot WIDTHxHEIGHT")?;
        let (w, h): (u16, u16) = (w.parse()?, h.parse()?);
        anyhow::ensure!(
            (1..=500).contains(&w) && (1..=200).contains(&h),
            "Snapshot size out of bounds"
        );
        while app.busy || app.pim_loading {
            app.event(events.recv().await.context("Worker stopped")?);
        }
        let mut terminal = ratatui::Terminal::new(ratatui::backend::TestBackend::new(w, h))?;
        terminal.draw(|f| mailtui::tui::draw(f, &mut app, config.ui.preview_pane))?;
        let buffer = terminal.backend().buffer();
        for y in 0..h {
            let line: String = (0..w).map(|x| buffer[(x, y)].symbol()).collect();
            println!("{line}");
        }
        drop(app);
        drop(events);
        worker.await?;
        return Ok(());
    }
    let mut terminal = ratatui::try_init()?;
    let result = async {
        execute!(std::io::stdout(), EnableBracketedPaste)?;
        let mut input = EventStream::new();
        let mut viewer: Option<Arc<Viewer>> = None;
        let (html_tx, mut html_rx) = tokio::sync::mpsc::channel::<Result<String>>(2);
        let (send_tx, mut send_rx) = tokio::sync::mpsc::channel(16);
        let mut sender = mailtui::delivery::Sender::new(config.delivery.clone(), config.accounts.clone(), send_tx);
        let (sync_tx, mut sync_rx) = tokio::sync::mpsc::channel(8);
        let mut synchronizer = mailtui::pim_sync::Synchronizer::new(config.calendars.clone(), config.tasks.clone(), sync_tx);
        let mut maintenance = index_path.clone().map(|path| mailtui::index::Maintenance::start(path, config.accounts.clone()));
        let mut index_requests = 0usize;
        let mut assistant = config.llm.enabled.then(|| mailtui::llm::Assistant::new(config.llm.clone(), config.accounts.clone(), args.demo, index_path.clone()).with_pim(config.calendar.clone(),config.contacts.clone()));
        let mut changes = (!args.demo).then(|| mailtui::storage::Changes::watch(config.accounts.clone()));
        let mut previous_tokens = None;
        let pim_paths = app.calendar_collections.iter().chain(&app.contact_books).chain(&app.task_collections).map(|collection| collection.path.clone()).collect::<Vec<_>>();
        let mut pim_changes = if pim_paths.is_empty() { None } else {
            match mailtui::pim_watch::Changes::start(pim_paths) {
                Ok(changes) => { app.pim_files_changed(); Some(changes) }
                Err(error) => { app.notify(format!("PIM directory watch: {error:#}")); None }
            }
        };
        let mut animation = tokio::time::interval(Duration::from_millis(300));
        let mut pim_clock = tokio::time::interval(Duration::from_secs(1));
        pim_clock.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Skip);
        animation.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Skip);
        loop {
            terminal.draw(|frame| mailtui::tui::draw(frame, &mut app, config.ui.preview_pane))?;
            if app.quit { break; }
            tokio::select! {
                _ = pim_clock.tick(), if !app.calendar_events.is_empty() => app.refresh_pim_clock(chrono::Utc::now()),
                result = async { pim_changes.as_mut().unwrap().events.recv().await }, if pim_changes.is_some() => {
                    if let Some(result) = result {
                        app.pim_files_changed();
                        if let Err(error) = result { app.notify(format!("PIM directory watch: {error}")); }
                    } else { pim_changes = None; }
                },
                result = sync_rx.recv() => if let Some(result) = result {
                    synchronizer.completed(result.target);
                    app.sync_completed(result.target, result.error);
                },
                event = async { assistant.as_mut().unwrap().events.recv().await }, if assistant.is_some() => if let Some(event) = event {
                    if event.run == app.ai.run && let mailtui::llm::Update::LoginUrl(url) = &event.update {
                        let command = &config.viewer.browser_command;
                        if config.viewer.mode != "manual" && std::env::var_os("SSH_CONNECTION").is_none() && std::env::var_os("SSH_TTY").is_none() {
                            let mut browser = tokio::process::Command::new(&command[0]);
                            browser.args(command[1..].iter().map(|arg| arg.replace("{url}",url))).stdin(std::process::Stdio::null()).stdout(std::process::Stdio::null()).stderr(std::process::Stdio::null()).kill_on_drop(true);
                            if let Ok(mut child) = browser.spawn() { tokio::spawn(async move { let _ = child.wait().await; }); }
                        }
                    }
                    app.ai_event(event);
                },
                _ = animation.tick(), if app.index_busy => {
                    if app.index_busy && matches!(app.overlay, Some(Overlay::Find { loading: false, .. })) { app.index_changed(); }
                },
                result = async { maintenance.as_mut().unwrap().events.recv().await }, if maintenance.is_some() => if let Some(result) = result {
                    index_requests = index_requests.saturating_sub(1);
                    app.index_busy = index_requests > 0;
                    if !matches!(&result, Ok(0)) { app.index_changed(); }
                    if let Err(error) = result { app.notify(format!("Local index: {error}")); }
                },
                tokens = async { changes.as_mut().unwrap().events.recv().await }, if changes.is_some() => if let Some(tokens) = tokens {
                    app.poll_pending();
                    app.index_dirty = true;
                    if previous_tokens.as_ref() != Some(&tokens) { app.storage_changed(); previous_tokens = Some(tokens); }
                },
                result = send_rx.recv() => if let Some(result) = result {
                    sender.completed(&result.account);
                    app.delivery_completed(result.account, result.error);
                },
                event = events.recv() => if let Some(event) = event { app.event(event); } else { anyhow::bail!("Background worker stopped"); },
                event = input.next() => match event {
                    Some(Ok(TerminalEvent::Key(key))) if key.kind != KeyEventKind::Release => app.key(key),
                    Some(Ok(TerminalEvent::Paste(text))) => app.paste(&text),
                    Some(Ok(TerminalEvent::Resize(..))) => {},
                    Some(Err(e)) => return Err(e.into()),
                    None => break,
                    _ => {}
                },
                result = html_rx.recv() => if let Some(result) = result {
                    match result {
                        Ok(url) => {
                            if config.viewer.mode == "manual" || std::env::var_os("SSH_CONNECTION").is_some() || std::env::var_os("SSH_TTY").is_some() { app.overlay = Some(Overlay::Url(url)); }
                            else {
                                let command = &config.viewer.browser_command;
                                let mut browser = tokio::process::Command::new(&command[0]);
                                browser.args(command[1..].iter().map(|arg| arg.replace("{url}", &url))).stdin(std::process::Stdio::null()).stdout(std::process::Stdio::null()).stderr(std::process::Stdio::null()).kill_on_drop(true);
                                match browser.spawn() {
                                    Ok(mut child) => { tokio::spawn(async move { let _ = child.wait().await; }); app.notify("Browser command started · page button toggles remote images"); }
                                    Err(_) => { app.notify("Browser launch failed; open the private URL manually"); app.overlay = Some(Overlay::Url(url)); }
                                }
                            }
                        }
                        Err(e) => app.notify(format!("Viewer error: {e}")),
                    }
                }
            }
            app.refresh_if_idle();
            app.refresh_pim_if_idle();
            for target in app.sync_requests.drain() { synchronizer.request(target); }
            for command in app.ai.commands.drain(..) { if let Some(assistant) = &mut assistant { assistant.request(command); } }
            for account in app.send_requests.drain() { if !args.demo { sender.request(&account); } }
            if app.index_dirty {
                if let Some(maintenance) = &maintenance {
                    if maintenance.request() { app.index_dirty = false; index_requests += 1; app.index_busy = true; }
                } else { app.index_dirty = false; }
            }
            if app.want_html {
                app.want_html = false;
                if let Some(parsed) = app.parsed.clone() {
                    if viewer.is_none() {
                        match Viewer::start(Duration::from_secs(config.viewer.session_ttl_seconds)).await { Ok(v) => viewer = Some(Arc::new(v)), Err(e) => { app.notify(format!("Cannot start viewer: {e}")); continue; } }
                    }
                    let viewer = viewer.as_ref().unwrap().clone();
                    let tx = html_tx.clone();
                    let remote = app.html_remote;
                    tokio::task::spawn_blocking(move || { let _ = tx.blocking_send(Ok(viewer.session_with_mode(&parsed, remote))); });
                    app.notify("Preparing sanitized HTML…");
                } else { app.notify("Wait for the message body before opening HTML"); }
            }
        }
        if let Some(viewer) = viewer { viewer.revoke(); }
        Ok::<_, anyhow::Error>(())
    }.await;
    let _ = execute!(std::io::stdout(), DisableBracketedPaste);
    ratatui::restore();
    current.fetch_add(1, Ordering::Relaxed);
    drop(app);
    drop(events);
    let _ = worker.await;
    result
}
